import playwright from '../../../apps/web/node_modules/playwright/index.js';
import fs from 'node:fs/promises';

const { chromium } = playwright;
const base = 'http://localhost:5173';
const out = new URL('./', import.meta.url);
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
const page = await context.newPage();
page.setDefaultTimeout(12000);
const log = { checks: [], events: [], states: {} };
const check = (name, pass, detail = '') => log.checks.push({ name, pass, detail });
const mainText = () => page.locator('main').innerText();
const shot = name => page.screenshot({ path: new URL(`${name}.png`, out).pathname, fullPage: true });
page.on('console', m => { if (!['debug', 'info'].includes(m.type())) log.events.push({ type: `console:${m.type()}`, text: m.text() }); });
page.on('requestfailed', r => log.events.push({ type: 'requestfailed', url: r.url(), failure: r.failure() }));
page.on('response', r => { if (r.status() >= 400) log.events.push({ type: 'http', status: r.status(), url: r.url() }); });

await page.goto(`${base}/today`, { waitUntil: 'networkidle' });
let text = await mainText();
check('welcome state', /Begin my first transformation/i.test(text), text);
check('primary nav exact', (await page.locator('nav a').allTextContents()).filter(x => ['Today','Journey','Library'].includes(x.trim())).join('|') === 'Today|Journey|Library', await page.locator('nav').innerText());
await page.getByText('More', { exact: true }).click();
text = await page.locator('header').innerText();
check('More destinations', ['Search','Knowledge','Memor','Settings'].every(x => text.includes(x)), text);
await page.keyboard.press('Escape');
await page.locator('body').press('Home');
await page.keyboard.press('Tab');
check('skip link first focus', /skip/i.test(await page.locator(':focus').innerText().catch(() => '')), await page.locator(':focus').evaluate(e => e.outerHTML).catch(() => ''));
await page.keyboard.press('Enter');
check('skip link target', await page.locator('#main-content').evaluate(e => e === document.activeElement), await page.locator(':focus').evaluate(e => e.outerHTML).catch(() => ''));
await shot('welcome-fixed');

await page.goto(`${base}/transformations`, { waitUntil: 'networkidle' });
const saveTransformation = page.getByRole('button', { name: 'Save transformation' });
check('blank transformation blocked', await saveTransformation.isDisabled(), 'disabled=' + await saveTransformation.isDisabled());
text = await mainText();
check('blank validation explained', /required|enter|provide|title/i.test(text), text);
const fields = page.locator('main input, main textarea');
await fields.nth(0).fill('Respond to feedback with calm curiosity');
await fields.nth(1).fill('I want criticism to become useful information instead of a verdict.');
await fields.nth(2).fill('Someone who listens, pauses, and chooses a thoughtful response.');
await fields.nth(3).fill('I react quickly when feedback feels personal.');
await saveTransformation.click();
await page.waitForTimeout(700);
text = await mainText();
check('transformation saved', /Respond to feedback with calm curiosity/.test(text), text);
await shot('transformation-created-fixed');

await page.getByRole('link', { name: 'Respond to feedback with calm curiosity' }).click();
await page.waitForTimeout(400);
await page.getByRole('button', { name: 'Draft this for me' }).click();
await page.waitForTimeout(700);
const detailFields = page.locator('main input, main textarea, main select');
const values = await detailFields.evaluateAll(es => es.map(e => e.value));
text = await mainText();
check('fallback draft fills required fields', values.slice(0,3).every(Boolean), JSON.stringify(values));
check('fallback provenance visible', /fallback|deterministic|AI unavailable|not AI/i.test(text), text);
await shot('experiment-draft-fixed');
await page.goto(`${base}/today`, { waitUntil: 'networkidle' });
check('draft navigation does not persist', /No active experiment yet/i.test(await mainText()), await mainText());

await page.goto(`${base}/transformations`, { waitUntil: 'networkidle' });
await page.getByRole('link', { name: 'Respond to feedback with calm curiosity' }).click();
await page.waitForTimeout(300);
const experimentFields = page.locator('main input, main textarea');
await experimentFields.nth(0).fill('Pause before responding to feedback');
await experimentFields.nth(1).fill('Whether one breath creates room for curiosity.');
await experimentFields.nth(2).fill('Take one breath, then ask one clarifying question.');
await experimentFields.nth(3).fill('Once during the next feedback conversation');
await experimentFields.nth(4).fill('I ask a question and regret less afterward.');
await page.getByRole('button', { name: 'Save experiment' }).click();
await page.waitForTimeout(700);
text = await mainText();
check('saved experiment confirmed on detail', /Pause before responding to feedback/.test(text) && /saved|experiment/i.test(text), text);
await shot('experiment-confirmation-fixed');
await page.goto(`${base}/today`, { waitUntil: 'networkidle' });
text = await mainText();
check('active experiment on Today', /Active experiment: Pause before responding to feedback/i.test(text), text);
await shot('today-active-fixed');

await page.setViewportSize({ width: 390, height: 844 });
await page.reload({ waitUntil: 'networkidle' });
const overflow = await page.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth);
check('mobile has no horizontal overflow', !overflow, `scrollWidth=${await page.evaluate(() => document.documentElement.scrollWidth)}, clientWidth=${await page.evaluate(() => document.documentElement.clientWidth)}`);
await shot('mobile-today-fixed');

await fs.writeFile(new URL('fallback-regression.json', out), JSON.stringify(log, null, 2));
console.log(JSON.stringify(log, null, 2));
await browser.close();
