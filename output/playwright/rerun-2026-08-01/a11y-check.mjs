import playwright from '../../../apps/web/node_modules/playwright/index.js';
import fs from 'node:fs/promises';
const { chromium } = playwright;
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const events = [];
page.on('console', m => { if (!['debug','info'].includes(m.type())) events.push({ type:`console:${m.type()}`, text:m.text() }); });
page.on('requestfailed', r => events.push({ type:'requestfailed', url:r.url(), failure:r.failure() }));
page.on('response', r => { if (r.status() >= 400) events.push({ type:'http', status:r.status(), url:r.url() }); });
await page.goto('http://localhost:5173/today', { waitUntil:'networkidle' });
await page.keyboard.press('Tab');
const first = await page.locator(':focus').evaluate(e => ({ text:e.textContent?.trim(), href:e.getAttribute('href'), outline:getComputedStyle(e).outline, boxShadow:getComputedStyle(e).boxShadow }));
await page.keyboard.press('Enter');
const target = await page.locator(':focus').evaluate(e => ({ id:e.id, tag:e.tagName, text:e.textContent?.trim().slice(0,80) }));
const active = await page.getByRole('link',{name:'Today'}).getAttribute('aria-current');
const unlabeled = await page.locator('main input,main textarea,main select').evaluateAll(es => es.filter(e => !e.labels?.length && !e.getAttribute('aria-label') && !e.getAttribute('aria-labelledby')).map(e => e.outerHTML));
const live = await page.locator('[aria-live]').evaluateAll(es => es.map(e => ({ live:e.getAttribute('aria-live'), text:e.textContent?.trim() })));
const result = { first, target, active, unlabeled, live, events };
await page.screenshot({ path:new URL('keyboard-focus.png',import.meta.url).pathname, fullPage:true });
await fs.writeFile(new URL('a11y-check.json',import.meta.url), JSON.stringify(result,null,2));
console.log(JSON.stringify(result,null,2));
await browser.close();
